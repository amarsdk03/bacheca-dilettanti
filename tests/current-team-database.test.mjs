import assert from "node:assert/strict";
import {existsSync, readFileSync} from "node:fs";
import {test} from "node:test";

const engine = new URL("../node_modules/.cache/interaction-tests/node_modules/@electric-sql/pglite/dist/index.js", import.meta.url);
const migration = readFileSync(new URL("../supabase/migrations/20261016194927_current_teams_tournaments_and_clean_profile_creation.sql", import.meta.url), "utf8");
const id = n => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;

test("current teams: authoritative inheritance, history, recreation and scoped cleanup", {skip: !existsSync(engine)}, async t => {
	const {PGlite} = await import(engine.href);
	const db = await PGlite.create();
	t.after(() => db.close());
	await db.exec(`
		create role anon; create role authenticated; create role service_role bypassrls;
		create schema private;
		create table public.utente(utente_uuid uuid, auth_user_uuid uuid, registrato_il timestamptz default now());
		create table public.profilo(uuid uuid primary key, uuid_utente uuid, nascosto boolean default false, link_foto_profilo text);
		create table public.profilo_giocatore(id bigint generated by default as identity primary key, uuid_profilo uuid, nascosto boolean default false, disponibilita text, categoria_attuale text, storico_carriera jsonb default '[]');
		create table public.profilo_squadra(id bigint generated by default as identity primary key, uuid_profilo uuid, nascosto boolean default false, nome_societa text, nominativo_anonimo boolean default false, categoria_attuale text);
		create table public.profilo_torneo_evento(id bigint generated by default as identity primary key, uuid_profilo uuid, nascosto boolean default false, nome_organizzazione text);
		create table public.localita_profilo(uuid_profilo uuid, sottoprofilo text, id_sottoprofilo bigint, regione text);
		create table public.link_social_profilo(uuid_profilo uuid, sottoprofilo text, id_sottoprofilo bigint, sublink text);
		create table public.media_profilo(id bigint generated always as identity, uuid_profilo uuid, sottoprofilo text, formato_media text, link_media text);
		create table public.annuncio(uuid uuid, autore_annuncio uuid);
		create function private.team_category_is_valid_v1(text) returns boolean language sql as $$ select $1='Calcio a 11 maschile::FIGC — Serie A' $$;
		create function private.public_profile_name_v1(text,boolean,text) returns text language sql as $$ select case when $2 then 'Squadra' else $3 end $$;
		create function private.save_owned_subprofile_internal_v1(p_user uuid,p_profile_type text,p_draft jsonb,p_locations jsonb) returns jsonb language plpgsql as $$
		declare v_profile_id uuid:=p_user; v_result jsonb:='{}';
		begin
		  if p_profile_type='giocatore' then update public.profilo_giocatore set disponibilita=p_draft->>'disponibilita',categoria_attuale=p_draft->>'categoria_attuale',storico_carriera=coalesce(p_draft->'storico_carriera','[]') where uuid_profilo=p_user; end if;
		  if p_profile_type='squadra' then update public.profilo_squadra set categoria_attuale=p_draft->>'categoria_attuale' where uuid_profilo=p_user; end if;
  return v_result;
		end; $$;
		create function public.publish_announcement_v2(uuid,p_payload jsonb,text,text,text) returns jsonb language plpgsql as $$
		declare v_result jsonb:='{"status":"error"}'; begin
  return v_result;
		end; $$;
		create function private.provision_auth_user_with_consents_v1(uuid,text,jsonb) returns void language plpgsql as $$ begin null; end; $$;
		create function private.provision_auth_user(p_user_id uuid,p_email text,p_payload jsonb) returns void language plpgsql as $$
		begin
  perform private.provision_auth_user_with_consents_v1(p_user_id, p_email, p_payload);
		end; $$;
	`);
	for (const table of ["staff_sportivo", "arbitro", "campi_impianti", "servizi_consulenze", "creator"]) {
		await db.exec(`create table public.profilo_${table}(id bigint generated by default as identity primary key, uuid_profilo uuid,nascosto boolean default false)`);
	}
	// Active data remains; old instances and absent subprofile data are discarded.
	for (let n = 1; n <= 4; n++) await db.query("insert into public.profilo(uuid,uuid_utente,link_foto_profilo) values($1,$1,'main.jpg')", [id(n)]);
	for (let n = 1; n <= 4; n++) await db.query("insert into public.utente(utente_uuid,auth_user_uuid) values($1,$1)", [id(n)]);
	await db.query("insert into public.profilo_squadra(id,uuid_profilo,nome_societa,categoria_attuale) values(10,$1,'ASD Roma','Calcio a 11 maschile::FIGC — Serie A')", [id(1)]);
	await db.query("insert into public.profilo_giocatore(id,uuid_profilo,disponibilita) values(20,$1,'sotto-contratto')", [id(2)]);
	await db.query("insert into public.profilo_torneo_evento(id,uuid_profilo,nome_organizzazione) values(30,$1,'Coppa Estate')", [id(3)]);
	await db.query("insert into public.link_social_profilo values($1,'squadra',10,'keep'),($1,'giocatore',999,'old')", [id(1)]);
	await db.query("insert into public.localita_profilo values($1,'squadra',10,'Lazio'),($1,'giocatore',999,'old')", [id(1)]);
	await db.exec(migration);
	const save = async (profile, type, draft) => db.query("select private.save_owned_subprofile_internal_v1($1,$2,$3,'[]')", [id(profile), type, JSON.stringify(draft)]);
	const player = async () => (await db.query("select * from public.profilo_giocatore where id=20")).rows[0];
	const draft = {disponibilita: "sotto-contratto", categoria_attuale: "FORGED", squadra_attuale_id: 10, squadra_attuale_nome: "FORGED", squadra_attuale_dal: "2024", storico_carriera: []};
	await save(2, "giocatore", draft);
	assert.equal((await player()).squadra_attuale_nome, "ASD Roma");
	assert.equal((await player()).categoria_attuale, "Calcio a 11 maschile::FIGC — Serie A");
	await db.query("select private.provision_auth_user($1,'test@example.com',$2)", [id(2), JSON.stringify({profiles: [{type: "giocatore", draft}]})]);
	assert.equal((await player()).squadra_attuale_id, 10);
	await db.query("insert into public.annuncio values($1,$2)", [id(100),id(2)]);
	await db.query("select private.finalize_current_team_fields_v1($1,$2)", [JSON.stringify({status: "success", announcementId: id(100)}), JSON.stringify({profile_type: "giocatore", profile_draft: null, profile_update: {draft}})]);
	assert.equal((await player()).squadra_attuale_nome, "ASD Roma");
	await save(1, "squadra", {categoria_attuale: "Calcio a 7 femminile::Tornei", torneo_attuale_id: 30, torneo_attuale_nome: "FORGED"});
	assert.equal((await player()).squadra_attuale_torneo, "Coppa Estate");
	assert.equal((await player()).categoria_attuale, "Calcio a 7 femminile::Tornei");
	await db.query("update public.profilo_torneo_evento set nome_organizzazione='Coppa Nuova' where id=30");
	assert.equal((await player()).squadra_attuale_torneo, "Coppa Nuova");
	await db.query("update public.profilo_squadra set nominativo_anonimo=true where id=10");
	assert.equal((await player()).squadra_attuale_nome, "Squadra");
	await save(2, "giocatore", {...draft, disponibilita: "svincolato", squadra_attuale_id: null, squadra_attuale_nome: null, categoria_attuale: null});
	let result = await player();
	assert.equal(result.squadra_attuale_id, null); assert.equal(result.categoria_attuale, null);
	assert.equal(result.storico_carriera[0].ente, "Coppa Nuova");
	assert.equal(result.storico_carriera[0].titolo, "Squadra");
	const year = new Intl.DateTimeFormat("en", {year: "numeric", timeZone: "Europe/Rome"}).format(new Date());
	assert.equal(result.storico_carriera[0].periodoA, year);
	await save(2, "giocatore", {...draft, squadra_attuale_id: null, squadra_attuale_nome: "Squadra manuale", categoria_attuale: "Categoria manuale", storico_carriera: result.storico_carriera});
	assert.equal((await player()).squadra_attuale_nome, "Squadra manuale");
	await assert.rejects(() => save(2, "giocatore", {...draft, squadra_attuale_id: 999}), /CURRENT_TEAM_UNAVAILABLE/);
	await save(2, "giocatore", {...draft, storico_carriera: (await player()).storico_carriera});
	await db.exec("delete from public.profilo_squadra where id=10");
	result = await player();
	assert.equal(result.squadra_attuale_id, null); assert.equal(result.squadra_attuale_nome, "Squadra");
	assert.equal(result.squadra_attuale_torneo, "Coppa Nuova");
	assert.equal((await db.query("select * from public.link_social_profilo where uuid_profilo=$1", [id(1)])).rows.length, 0);
	assert.equal((await db.query("select * from public.localita_profilo where uuid_profilo=$1", [id(1)])).rows.length, 0);
	await db.query("insert into public.profilo_squadra(id,uuid_profilo,nome_societa) values(11,$1,'Ricreata')", [id(1)]);
	assert.equal((await player()).squadra_attuale_id, null);
	assert.equal((await db.query("select link_media from public.media_profilo where uuid_profilo=$1", [id(1)])).rows[0].link_media, "");
	assert.equal((await db.query("select link_foto_profilo from public.profilo where uuid=$1", [id(1)])).rows[0].link_foto_profilo, "main.jpg");
	await db.query("insert into public.media_profilo(uuid_profilo,sottoprofilo,formato_media,link_media) values($1,null,'video_highlights','old-video')", [id(2)]);
	await db.exec("delete from public.profilo_giocatore where id=20");
	assert.equal((await db.query("select * from public.media_profilo where uuid_profilo=$1", [id(2)])).rows.length, 0);
	await db.exec("set role anon");
	await assert.rejects(() => save(1, "squadra", {}), {code: "42501"});
});
