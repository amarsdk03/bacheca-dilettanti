import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const root = new URL("../../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const sha = text => createHash("sha256").update(text).digest("hex");
export const m06Sha256 = "290a816f6ac297ef8234549ea0a08fae9a7475d2823e300665f8a2fadf9497aa";
export const migrationSha256 = "0afed5cbddb38219037672c6595c725bc3131e2e7287cf27f460609f5d2aa9da";

// Keep the reviewed M06 checks intact in the same READ ONLY snapshot. Updating
// their source requires explicit review, not automatic widening of accepted hashes.
export function buildM07Inventory() {
  const source = read("supabase/scripts/dashboard_admin_check_m06.sql");
  if (sha(source) !== m06Sha256) throw new Error("M06_INSPECTOR_SOURCE_REVIEW_REQUIRED");
  if (sha(read("supabase/migrations/20261024162714_admin_announcement_trash.sql")) !== migrationSha256) {
    throw new Error("M07_MIGRATION_SOURCE_REVIEW_REQUIRED");
  }
  const normalized = source.replaceAll("\r\n", "\n");
  const start = normalized.indexOf("begin read only;");
  const final = normalized.indexOf("\nselect jsonb_build_object('report_version',3");
  const end = normalized.lastIndexOf(";\nrollback;");
  if (start < 0 || final < start || end < final) throw new Error("M06_INSPECTOR_FORMAT_REVIEW_REQUIRED");
  return `-- M07A: INITIAL INVENTORY ONLY. Run the ENTIRE file as postgres.
-- Webapp Bacheca Dilettanti / nsytraextbndfyprwzts, Free; verify destination separately.
-- Generated by scripts/dashboard-integration/build-m07-inventory.mjs.
-- Catalogs only; no application function, row, gate value, audit or Cron job accessed.
-- Never authorizes migration/activation and never certifies the post-M07 state.
-- M06 checks below are reused unchanged; do not replay M06/M06A/M05 after M07.
${normalized.slice(start, final)},
m06_inventory_baseline as (
${normalized.slice(final, end).trim()}
),
${inventorySql}
rollback;
`;
}

