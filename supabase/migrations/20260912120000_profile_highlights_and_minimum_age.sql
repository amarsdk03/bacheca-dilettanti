create or replace function private.delete_player_highlights_v1()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  delete from public.media_profilo
  where uuid_profilo = old.uuid_profilo
    and formato_media = 'video_highlights';
  return old;
end;
$$;

