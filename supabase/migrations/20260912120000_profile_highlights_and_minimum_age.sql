create or replace function public.publish_announcement_v2(
  p_submission_id uuid,
  p_payload jsonb,
  p_terms_version text,
  p_privacy_version text,
  p_visibility text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_result jsonb;
  v_profile_id uuid;
  v_anonymous_at_publish boolean;
  v_is_retry boolean;
begin
  if (select auth.uid()) is null then
    raise exception using errcode = '28000', message = 'AUTH_REQUIRED';
  end if;

  v_result := private.publish_announcement_core_v2(
    p_submission_id,
    p_payload,
    p_terms_version,
    p_privacy_version,
    p_visibility
  );

  if v_result ->> 'status' <> 'success' then
    return v_result;
  end if;

  v_is_retry := coalesce((v_result ->> 'idempotent')::boolean, false);
  if v_is_retry or p_payload ->> 'profile_type' <> 'giocatore' then
    return v_result;
  end if;

  select announcement.autore_annuncio, submission.anonymous_at_publish
  into v_profile_id, v_anonymous_at_publish
  from private.announcement_submission as submission
  join public.annuncio as announcement
    on announcement.uuid = submission.announcement_id
  where submission.submission_id = p_submission_id;

  if v_anonymous_at_publish then
    perform private.save_player_highlights_for_profile_v1(
      v_profile_id,
      'giocatore',
      p_payload -> 'profile_draft'
    );
  end if;

  return v_result;
end;
$$;

revoke all on function public.publish_announcement_v2(uuid, jsonb, text, text, text)
  from public, anon, authenticated, service_role;
grant execute on function public.publish_announcement_v2(uuid, jsonb, text, text, text)
  to authenticated;

create or replace function private.validate_profile_birth_date_v1()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_year_text text := nullif(pg_catalog.btrim(new.anno_nascita), '');
  v_month_text text := nullif(pg_catalog.btrim(new.mese_nascita), '');
  v_day_text text := nullif(pg_catalog.btrim(new.giorno_nascita), '');
  v_year integer;
  v_month integer;
  v_day integer;
  v_max_day integer;
  v_cutoff date := ((pg_catalog.statement_timestamp() at time zone 'Europe/Rome')::date - interval '14 years')::date;
begin
  if v_year_text is null and v_month_text is null and v_day_text is null then
    return new;
  end if;

  if v_year_text is null or v_year_text !~ '^[0-9]{4}$' then
    raise exception using errcode = '22023', message = 'INVALID_BIRTH_DATE';
  end if;
  v_year := v_year_text::integer;
  if v_year < 1900 then
    raise exception using errcode = '22023', message = 'INVALID_BIRTH_DATE';
  end if;

  v_month := case v_month_text
    when 'Gennaio' then 1
    when 'Febbraio' then 2
    when 'Marzo' then 3
    when 'Aprile' then 4
    when 'Maggio' then 5
    when 'Giugno' then 6
    when 'Luglio' then 7
    when 'Agosto' then 8
    when 'Settembre' then 9
    when 'Ottobre' then 10
    when 'Novembre' then 11
    when 'Dicembre' then 12
    else null
  end;

  if v_month_text is not null and v_month is null then
    raise exception using errcode = '22023', message = 'INVALID_BIRTH_DATE';
  end if;
  if v_day_text is not null and (
    v_month is null
    or v_day_text !~ '^[0-9]{1,2}$'
  ) then
    raise exception using errcode = '22023', message = 'INVALID_BIRTH_DATE';
  end if;

  if v_day_text is not null then
    v_day := v_day_text::integer;
    v_max_day := extract(day from (
      pg_catalog.make_date(v_year, v_month, 1)
      + interval '1 month'
      - interval '1 day'
    ))::integer;
    if v_day < 1 or v_day > v_max_day then
      raise exception using errcode = '22023', message = 'INVALID_BIRTH_DATE';
    end if;
  end if;

  if v_year > extract(year from v_cutoff)::integer then
    raise exception using errcode = '22023', message = 'MINIMUM_AGE_REQUIRED';
  end if;

  if v_year = extract(year from v_cutoff)::integer then
    if v_month is null
      or v_month > extract(month from v_cutoff)::integer
      or (
        v_month = extract(month from v_cutoff)::integer
        and (v_day is null or v_day > extract(day from v_cutoff)::integer)
      ) then
      raise exception using errcode = '22023', message = 'MINIMUM_AGE_REQUIRED';
    end if;
  end if;

  return new;
end;
$$;

revoke all on function private.validate_profile_birth_date_v1()
  from public, anon, authenticated, service_role;

