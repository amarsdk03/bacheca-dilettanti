create or replace function private.save_owned_subprofile_internal_v1(
  p_internal_user_id uuid,
  p_profile_type text,
  p_draft jsonb,
  p_locations jsonb
)
returns jsonb
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_profile_id uuid;
  v_result jsonb;
begin
  v_result := private.save_owned_subprofile_core_v1(
    p_internal_user_id,
    p_profile_type,
    p_draft,
    p_locations
  );

  if p_profile_type = 'giocatore' then
    select uuid
    into v_profile_id
    from public.profilo
    where uuid_utente = p_internal_user_id;

    perform private.save_player_highlights_for_profile_v1(
      v_profile_id,
      p_profile_type,
      p_draft
    );
  end if;

  return v_result;
end;
$$;

