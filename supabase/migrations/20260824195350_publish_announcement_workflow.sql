create or replace function private.publish_object_has_only_keys(
  p_value jsonb,
  p_allowed_keys text[],
  p_required_keys text[] default array[]::text[]
)
returns boolean
language sql
immutable
parallel safe
security invoker
set search_path = ''
as $$
  select case
    when p_value is null or pg_catalog.jsonb_typeof(p_value) <> 'object' then false
    else
      p_value ?& p_required_keys
      and not exists (
        select 1
        from pg_catalog.jsonb_object_keys(p_value) as object_key(name)
        where not (object_key.name = any (p_allowed_keys))
      )
  end;
$$;

revoke all on function private.publish_object_has_only_keys(jsonb, text[], text[])
  from public, anon, authenticated, service_role;

create or replace function private.publish_text_array_is_valid(
  p_value jsonb,
  p_required boolean default false,
  p_max_items integer default 32,
  p_max_length integer default 120
)
returns boolean
language sql
immutable
parallel safe
security invoker
set search_path = ''
as $$
  select case
    when p_value is null then not p_required
    when pg_catalog.jsonb_typeof(p_value) <> 'array' then false
    else
      pg_catalog.jsonb_array_length(p_value) <= p_max_items
      and (not p_required or pg_catalog.jsonb_array_length(p_value) > 0)
      and not exists (
        select 1
        from pg_catalog.jsonb_array_elements(p_value) as item(value)
        where pg_catalog.jsonb_typeof(item.value) <> 'string'
          or pg_catalog.char_length(pg_catalog.btrim(item.value #>> '{}')) not between 1 and p_max_length
      )
      and (
        select pg_catalog.count(*) = pg_catalog.count(distinct pg_catalog.btrim(item.value #>> '{}'))
        from pg_catalog.jsonb_array_elements(p_value) as item(value)
      )
  end;
$$;

revoke all on function private.publish_text_array_is_valid(jsonb, boolean, integer, integer)
  from public, anon, authenticated, service_role;

create or replace function private.publish_locations_are_valid(p_value jsonb)
returns boolean
language sql
immutable
parallel safe
security invoker
set search_path = ''
as $$
  select case
    when p_value is null or pg_catalog.jsonb_typeof(p_value) <> 'array' then false
    when pg_catalog.jsonb_array_length(p_value) not between 1 and 100 then false
    else
      not exists (
        select 1
        from pg_catalog.jsonb_array_elements(p_value) as location(value)
        where not private.publish_object_has_only_keys(
          location.value,
          array['regione', 'citta'],
          array['regione']
        )
          or pg_catalog.jsonb_typeof(location.value -> 'regione') <> 'string'
          or (
            location.value ? 'citta'
            and pg_catalog.jsonb_typeof(location.value -> 'citta') not in ('string', 'null')
          )
          or nullif(pg_catalog.btrim(location.value ->> 'regione'), '') is null
          or pg_catalog.char_length(pg_catalog.btrim(location.value ->> 'regione')) > 80
          or pg_catalog.char_length(pg_catalog.btrim(coalesce(location.value ->> 'citta', ''))) > 120
      )
      and (
        select pg_catalog.count(*) = pg_catalog.count(
          distinct pg_catalog.jsonb_build_array(
            pg_catalog.btrim(location.value ->> 'regione'),
            nullif(pg_catalog.btrim(location.value ->> 'citta'), '')
          )
        )
        from pg_catalog.jsonb_array_elements(p_value) as location(value)
      )
  end;
$$;

revoke all on function private.publish_locations_are_valid(jsonb)
  from public, anon, authenticated, service_role;

