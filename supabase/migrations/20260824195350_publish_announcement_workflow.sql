  p_locations jsonb
)
returns uuid
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_profile_id uuid;
  v_subprofile_id bigint;
begin
  if p_draft is null
    or p_locations is null
    or p_profile_type is null
    or p_profile_type not in (
    'giocatore',
    'squadra',
    'staff-sportivo',
    'arbitro',
    'torneo-evento',
    'campi-impianti-sportivi'
  )
    or pg_catalog.jsonb_typeof(p_draft) <> 'object'
    or not private.publish_locations_are_valid(p_locations)
    or pg_catalog.pg_column_size(p_draft) > 128000 then
    raise exception using errcode = '22023', message = 'INVALID_PUBLISH_PAYLOAD';
  end if;

  if (
    case p_profile_type
    when 'giocatore' then
      not private.publish_text_is_valid(p_draft ->> 'nome', true, 160)
      or not private.publish_text_array_is_valid(p_draft -> 'tipologie_sport', true)
      or pg_catalog.jsonb_typeof(p_draft -> 'ruoli_sport') <> 'object'
      or not private.publish_text_array_is_valid(p_draft -> 'ruoli_sport' -> 'principali', true)
    when 'squadra' then
      not private.publish_text_is_valid(p_draft ->> 'nome_societa', true, 160)
      or not private.publish_text_array_is_valid(p_draft -> 'tipologie_sport', true)
