        v_profile_id,
        p_draft ->> 'sport_principale',
        p_draft ->> 'nome_organizzazione',
        array(select jsonb_array_elements_text(coalesce(p_draft -> 'tipologie_sport', '[]'::jsonb))),
        p_draft ->> 'sede_principale',
        p_draft ->> 'presentazione',
        p_draft -> 'orari',
        nullif(pg_catalog.btrim(p_draft ->> 'costo_partenza'), '')::numeric(10, 2),
        p_draft ->> 'servizi_inclusi',
        p_draft ->> 'info_aggiuntive',
        false
      ) returning id into v_subprofile_id;
  end case;

  insert into public.localita_profilo (
    uuid_profilo,
    sottoprofilo,
    id_sottoprofilo,
    regione,
    citta
  )
  select
    v_profile_id,
    p_profile_type,
    v_subprofile_id,
    pg_catalog.btrim(location.value ->> 'regione'),
    nullif(pg_catalog.btrim(location.value ->> 'citta'), '')
  from pg_catalog.jsonb_array_elements(p_locations) as location(value);

  return v_profile_id;
end;
$$;

